function toChineseChapterNumeral(n) {
    const digits = ['零', '一', '二', '三', '四', '五', '六', '七', '八', '九'];
    if (n <= 0 || n > 99) return String(n);
    if (n < 10) return digits[n];
    if (n === 10) return '十';
    if (n < 20) return '十' + digits[n - 10];
    const tens = Math.floor(n / 10);
    const ones = n % 10;
    if (ones === 0) return digits[tens] + '十';
    return digits[tens] + '十' + digits[ones];
}

function formatWorkChapterTitle(num, lang) {
    if (window.HANQIAO && typeof window.HANQIAO.formatWorkChapterTitle === 'function') {
        return window.HANQIAO.formatWorkChapterTitle(num, lang);
    }
    switch (lang) {
        case 'es':
            return 'Capítulo ' + num;
        case 'pt':
            return 'Capítulo ' + num;
        case 'it':
            return 'Capitolo ' + num;
        case 'de':
            return 'Kapitel ' + num;
        case 'la':
            return 'Capitulum ' + num;
        default:
            return '第' + toChineseChapterNumeral(num) + '章';
    }
}

