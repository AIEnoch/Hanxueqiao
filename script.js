function articlePickLang(obj, lang) {
    if (!obj || typeof obj !== 'object') return '';
    if (obj[lang]) return obj[lang];
    if (lang === 'de') {
        const it = obj.it || '';
        const es = obj.es || '';
        const pt = obj.pt || '';
        const source = it || es || pt || obj.zh || '';
        const mapped = String(source)
            .replace(/^Capitolo\s+/i, 'Kapitel ')
            .replace('Classico taoista. Ingressi per capitolo con testo, commento, traduzioni ES/PT/IT e confronto culturale.', 'Daoistischer Klassiker. Kapitelzugänge mit Text, Kommentar, ES/PT/IT/DE-Ubersetzungen und interkulturellem Vergleich.')
            .replace('Dao e nome; commento e termini.', 'Dao und Benennung; Kommentar und Begriffsanmerkungen.')
            .replace('Relatività e non-azione.', 'Relativität und Nicht-Erzwingen.')
            .replace('Capitolo disponibile come pagina dinamica; si possono aggiungere dopo commenti più estesi.', 'Kapitel als dynamische Seite verfügbar; vertiefte Kommentare können ergänzt werden.');
        return mapped || obj.zh || '';
    }
    if (lang === 'la') {
        const source = obj.la || obj.it || obj.es || obj.pt || obj.de || obj.zh || '';
        const mapped = String(source)
            .replace(/^Capitolo\s+/i, 'Capitulum ')
            .replace(/^Capítulo\s+/i, 'Capitulum ')
            .replace(/^Kapitel\s+/i, 'Capitulum ')
            .replace(/^第(.+)章$/i, 'Caput $1')
            .replace('Classico taoista. Ingressi per capitolo con testo, commento, traduzioni ES/PT/IT e confronto culturale.', 'Classicum Daoisticum. Accessus per capita cum textu, commentario, interpretationibus ES/PT/IT/LA/DE et comparatione interculturali.')
            .replace('Dao e nome; commento e termini.', 'Dao et nomen; commentarium et annotationes terminorum.')
            .replace('Relatività e non-azione.', 'Relativitas et non-actio.')
            .replace('Capitolo disponibile come pagina dinamica; si possono aggiungere dopo commenti più estesi.', 'Capitulum in pagina dynamica praesto est; commentaria ampliora postea addi possunt.');
        return mapped || obj.zh || '';
    }
    return obj.zh || '';
}

function articleMatchesQuery(article, q, includeChapterHay = true) {
    const needle = q.trim().toLowerCase();
    if (!needle) return true;
    const searchBlob =
        article.searchText == null
            ? ''
            : typeof article.searchText === 'string'
              ? article.searchText
              : Object.values(article.searchText).join(' ');
    let chapterHay = '';
    if (includeChapterHay && article.kind === 'work' && Array.isArray(article.chapters)) {
        chapterHay = article.chapters
            .flatMap((ch) => [
                ch.chapterWorkId || '',
                ch.pathSegment || '',
                ...Object.values(ch.title || {}),
                ...Object.values(ch.summary || {})
            ])
            .join(' ');
    }
    const hay = [
        article.keywords || '',
        article.id || '',
        article.work || '',
        article.chapter || '',
        ...Object.values(article.title || {}),
        ...Object.values(article.summary || {}),
        searchBlob,
        chapterHay
    ]
        .join(' ')
        .toLowerCase();
    const tokens = needle.split(/\s+/).filter(Boolean);
    if (!tokens.length) return true;
    return tokens.every((t) => hay.includes(t));
}

function renderArticleSearchResults() {
    const container = document.getElementById('articleSearchResults');
    const input = document.getElementById('articleSearchInput');
    if (!container || !window.ARTICLES) return;

    const lang = getUiLang();
    const dict = getI18nDict(lang);
    const q = input ? input.value : '';
    const list = q.trim()
        ? window.ARTICLES.flatMap((work) => {
              const matchingChapters = (work.chapters || []).filter((chapter) =>
                  articleMatchesQuery(chapter, q)
              );
              if (matchingChapters.length) return matchingChapters;
              return articleMatchesQuery(work, q, false) ? [work] : [];
          })
        : [];

    const renderList = (items) =>
        '<ul class="search-results-list">' +
        items
            .map((a) => {
                const title = articlePickLang(a.title, lang);
                const sum = articlePickLang(a.summary, lang);
                const descHtml = sum && String(sum).trim()
                    ? `<span class="search-result-desc">${escapeHtml(sum)}</span>`
                    : '';
                if (a.available && a.hub) {
                    const hubUrl = withLangParam(a.hub, lang);
                    return (
                        `<li class="search-result-card">` +
                        `<a class="search-result-main" href="${hubUrl}"><strong>${escapeHtml(title)}</strong>` +
                        descHtml +
                        `</a>` +
                        `</li>`
                    );
                }
                return (
                    `<li class="search-result-card search-result-soon">` +
                    `<strong>${escapeHtml(title)}</strong>` +
                    `<span class="search-result-badge">${escapeHtml(dict.searchStatusPlanned || '')}</span>` +
                    (sum && String(sum).trim()
                        ? `<p class="search-result-desc">${escapeHtml(sum)}</p>`
                        : '') +
                    `</li>`
                );
            })
            .join('') +
        '</ul>';

    if (!q.trim()) {
        const hint = dict.searchHint && String(dict.searchHint).trim();
        container.innerHTML = hint ? `<p class="search-results-meta">${escapeHtml(hint)}</p>` : '';
    } else if (!list.length) {
        container.innerHTML = `<p class="search-results-empty">${escapeHtml(dict.searchNoResults || '')}</p>`;
    } else {
        container.innerHTML = renderList(list);
    }
}

