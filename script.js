function applyI18n(lang) {
    const dict = getI18nDict(lang);

    const titleEl = document.querySelector('title');
    if (titleEl && !document.body.hasAttribute('data-skip-i18n-title')) {
        const titleKey = titleEl.getAttribute('data-i18n');
        if (titleKey && dict[titleKey] != null) {
            titleEl.textContent = dict[titleKey];
        } else if (dict.docTitle) {
            titleEl.textContent = dict.docTitle;
        }
    }

    document.querySelectorAll('[data-i18n]').forEach((el) => {
        const key = el.getAttribute('data-i18n');
        if (key && dict[key] != null) el.textContent = dict[key];
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (key && dict[key] != null) el.setAttribute('placeholder', dict[key]);
    });

    document.querySelectorAll('[data-i18n-html]').forEach((el) => {
        const key = el.getAttribute('data-i18n-html');
        if (key && dict[key] != null) el.innerHTML = dict[key];
    });

    document.querySelectorAll('[data-i18n-aria-label]').forEach((el) => {
        const key = el.getAttribute('data-i18n-aria-label');
        if (key && dict[key] != null) el.setAttribute('aria-label', dict[key]);
    });

    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : lang;

    document.querySelectorAll('.lang-btn').forEach((btn) => {
        const on = btn.getAttribute('data-lang') === lang;
        btn.classList.toggle('active', on);
        btn.setAttribute('aria-pressed', on ? 'true' : 'false');
    });
}

