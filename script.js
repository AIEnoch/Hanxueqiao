function getWorkLayer(lang) {
    const widRaw = typeof document !== 'undefined' && document.body?.dataset?.workId;
    const wid =
        widRaw != null && String(widRaw).trim() !== '' ? String(widRaw).trim() : '';
    if (!wid || typeof window === 'undefined' || !window.WORK_COPY || !window.WORK_COPY[wid]) return {};
    const w = window.WORK_COPY[wid];
    const base = w.zh && typeof w.zh === 'object' ? w.zh : {};
    const langOverlay = lang !== 'zh' && w[lang] && typeof w[lang] === 'object' ? w[lang] : null;
    const itOverlay = lang === 'la' && w.it && typeof w.it === 'object' ? w.it : null;
    const raw = lang === 'la' ? { ...base, ...(itOverlay || {}), ...(langOverlay || {}) } : langOverlay ? { ...base, ...langOverlay } : { ...base };
    const out = {};
    for (const [k, v] of Object.entries(raw)) {
        if (v != null && String(v).trim() !== '') out[k] = v;
    }
    return out;
}

