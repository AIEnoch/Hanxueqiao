function initSearchCharPicker() {
    const input = document.getElementById('articleSearchInput');
    const panel = document.querySelector('.search-chars');
    if (!input || !panel) return;
    if (panel.dataset.boundCharPicker === '1') return;
    panel.dataset.boundCharPicker = '1';

    panel.addEventListener('click', function (e) {
        const btn = e.target.closest('[data-insert-char]');
        if (!btn || !panel.contains(btn)) return;
        e.preventDefault();
        const ch = btn.getAttribute('data-insert-char');
        if (!ch) return;

        const start = input.selectionStart != null ? input.selectionStart : input.value.length;
        const end = input.selectionEnd != null ? input.selectionEnd : input.value.length;
        const v = input.value;
        input.value = v.slice(0, start) + ch + v.slice(end);
        const pos = start + ch.length;
        input.focus();
        try {
            input.setSelectionRange(pos, pos);
        } catch (err) {
            /* ignore */
        }
        input.dispatchEvent(new Event('input', { bubbles: true }));
    });
}

