function normalizeUiLang(want) {
    const allowed = getAllowedUiLangsFromDom();
    if (!want) return 'zh';
    const w = String(want).trim().toLowerCase();
    if (!allowed.size) return w === 'zh' ? 'zh' : w;
    return allowed.has(w) ? w : 'zh';
}

function getInitialUiLang() {
    const params = new URLSearchParams(window.location.search);
    const fromUrl = params.get('lang');
    if (fromUrl) return normalizeUiLang(fromUrl);
    try {
        const stored = localStorage.getItem(UI_LANG_STORAGE_KEY);
        if (stored) return normalizeUiLang(stored);
    } catch (e) {
        /* ignore */
    }
    return 'zh';
}

function persistUiLang(lang) {
    try {
        localStorage.setItem(UI_LANG_STORAGE_KEY, lang);
    } catch (e) {
        /* ignore */
    }
}

function setUrlLangParam(lang) {
    const url = new URL(window.location.href);
    if (lang && lang !== 'zh') url.searchParams.set('lang', lang);
    else url.searchParams.delete('lang');
    history.replaceState({}, '', url.toString());
}

function withLangParam(rawHref, lang) {
    if (!rawHref) return rawHref;
    if (rawHref.startsWith('#')) return rawHref;
    if (/^(mailto:|tel:|javascript:)/i.test(rawHref)) return rawHref;
    let u;
    try {
        u = new URL(rawHref, window.location.href);
    } catch (e) {
        return rawHref;
    }
    if (u.origin !== window.location.origin) return rawHref;
    if (lang && lang !== 'zh') u.searchParams.set('lang', lang);
    else u.searchParams.delete('lang');
    const sameOrigin = u.origin === window.location.origin;
    return sameOrigin ? `${u.pathname}${u.search}${u.hash}` : u.toString();
}

function syncInternalLangLinks(lang) {
    document.querySelectorAll('a[href]').forEach((a) => {
        const href = a.getAttribute('href');
        if (!href) return;
        const next = withLangParam(href, lang);
        if (next && next !== href) a.setAttribute('href', next);
    });
}

