function getI18nDict(lang) {
    const base = I18N.zh;
    const overlay = lang !== 'zh' && I18N[lang] ? I18N[lang] : null;
    let dict = overlay ? { ...base, ...overlay } : { ...base };
    const workLayer = getWorkLayer(lang);
    if (lang === 'de') {
        Object.keys(workLayer).forEach((k) => {
            if (dict[k] == null || String(dict[k]).trim() === '') dict[k] = workLayer[k];
        });
        const langFlatDe = getRawChapterLangFlat('de');
        Object.keys(langFlatDe).forEach((k) => {
            const v = langFlatDe[k];
            if (v != null && String(v).trim() !== '') dict[k] = v;
        });
    } else {
        dict = { ...dict, ...workLayer };
    }
    if (lang !== 'zh') {
        const zhWork = getWorkLayer('zh');
        const zhGlobal = I18N.zh;
        const langFlat = getRawChapterLangFlat(lang);
        const keys = new Set([...Object.keys(zhGlobal), ...Object.keys(zhWork), ...Object.keys(langFlat)]);
        keys.forEach((key) => {
            if (!shouldUseZhOnlyForModule23(key, lang)) return;
            const fromLang = langFlat[key];
            if (fromLang != null && String(fromLang).trim() !== '') {
                dict[key] = fromLang;
                return;
            }
            const fromWork = zhWork[key];
            const fromGlobal = zhGlobal[key];
            if (fromWork != null && String(fromWork).trim() !== '') dict[key] = fromWork;
            else if (fromGlobal != null) dict[key] = fromGlobal;
        });
    }
    return dict;
}

